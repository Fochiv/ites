function language_url(string $lang): string
{
    $page = basename((string) ($_SERVER['PHP_SELF'] ?? 'index.php'));
    return e($page . '?lang=' . rawurlencode($lang));
}

function start_contact_session(): void
{
    if (session_status() === PHP_SESSION_ACTIVE) {
        return;
    }

    $forwardedProto = strtolower(trim(explode(',', (string) ($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? ''))[0]));
    $isHttps =
        (isset($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== '' && $_SERVER['HTTPS'] !== 'off') ||
        $forwardedProto === 'https';
    session_set_cookie_params([
        'httponly' => true,
        'secure' => $isHttps,
        'samesite' => 'Lax',
        'path' => '/',
    ]);
    session_start();
}

function contact_csrf_token(): string
{
    start_contact_session();

    if (!isset($_SESSION['contact_csrf']) || !is_string($_SESSION['contact_csrf'])) {
        $_SESSION['contact_csrf'] = bin2hex(random_bytes(32));
    }

    return $_SESSION['contact_csrf'];
}

function contact_text_length(string $value): int
{
    return function_exists('mb_strlen') ? mb_strlen($value, 'UTF-8') : strlen($value);
}
